"use client";

import { motion, AnimatePresence } from "framer-motion";
import { Tabs, TabsContent, TabsList } from "@/components/ui/tabs";
import { UrlInput } from "@/components/url-input";
import { ArchitectureDiagram } from "@/components/architecture-diagram";
import { DependencyGraph } from "@/components/dependency-graph";
import { RefactorsPanel } from "@/components/refactors-panel";
import { AutomationsPanel } from "@/components/automations-panel";
import { IssuesPanel, SuggestedIssue } from "@/components/issues-panel";
import { AnalysisHeader } from "@/components/analysis-header";
import { LoadingSkeleton } from "@/components/loading-skeleton";
import { RecentAnalyses } from "@/components/recent-analyses";
import { useAnalysis } from "@/hooks/use-analysis";
import { Button } from "@/components/ui/button";
import { Card, CardContent } from "@/components/ui/card";
import { ScrollArea, ScrollBar } from "@/components/ui/scroll-area";
import { Badge } from "@/components/ui/badge";
import { cn } from "@/lib/utils";
import {
  AlertCircle,
  RotateCcw,
  GitBranch,
  Workflow,
  Wrench,
  Zap,
  RefreshCw,
  Database,
  Bug,
  Github,
  ArrowRight,
} from "lucide-react";
import { useMemo } from "react";

import { fadeIn, slideUp } from "./animations";
import { SectionHeader } from "./section-header";
import { TabTriggerItem } from "./tab-trigger-item";
import { EmptyState } from "./empty-state";

export function RepoAnalyzer() {
  const {
    analyze,
    analyzeBranch,
    status,
    result,
    reset,
    refresh,
    isLoading,
    isComplete,
    hasError,
    isIdle,
    isCached,
    currentBranch,
  } = useAnalysis();

  const handleReset = () => {
    reset();
    window.scrollTo({
      top: 0,
      behavior: "smooth",
    });
  };

  // Generate suggested issues from analysis results
  const suggestedIssues = useMemo((): SuggestedIssue[] => {
    if (!result) return [];

    const issues: SuggestedIssue[] = [];

    // Convert insights to issues
    result.insights?.forEach((insight, index) => {
      if (insight.type === "weakness" || insight.type === "warning") {
        const issueType: SuggestedIssue["type"] =
          insight.type === "warning" ? "bug" : "improvement";
        const priority: SuggestedIssue["priority"] =
          insight.priority === "critical"
            ? "critical"
            : insight.priority === "high"
              ? "high"
              : insight.priority === "medium"
                ? "medium"
                : "low";

        issues.push({
          id: `insight-${index}`,
          type: issueType,
          title: insight.title,
          description: insight.description,
          body: `## ${insight.title}

### Category
${insight.category}

### Description
${insight.description}

### Priority
${insight.priority}

${
  insight.affectedFiles?.length
    ? `### Affected Files
${insight.affectedFiles.map((f) => `- \`${f}\``).join("\n")}`
    : ""
}

---
*Generated by Argos analysis*`,
          labels: [
            insight.type === "warning" ? "bug" : "enhancement",
            insight.category?.toLowerCase().replace(/\s+/g, "-") || "general",
            `priority-${insight.priority}`,
          ].filter(Boolean),
          priority,
          source: "insight",
          affectedFiles: insight.affectedFiles,
        });
      }
    });

    // Convert high-priority automations to issues
    result.automations?.forEach((automation, index) => {
      if (automation.priority === "high" && automation.type === "issue") {
        issues.push({
          id: `automation-${index}`,
          type: "improvement",
          title: automation.title,
          description: automation.description,
          body: automation.body,
          labels: automation.labels || ["enhancement"],
          priority: "high",
          source: "automation",
          estimatedEffort: (automation as { estimatedEffort?: string })
            .estimatedEffort,
          affectedFiles: (automation as { files?: string[] }).files,
        });
      }
    });

    return issues;
  }, [result]);

  return (
    <div className="w-full">
      <div className="space-y-7 sm:space-y-9">
        <section className="w-full">
          <UrlInput onAnalyze={analyze} isLoading={isLoading} />
        </section>

        <AnimatePresence mode="wait">
          {hasError && (
            <motion.section
              key="error"
              variants={slideUp}
              initial="hidden"
              animate="visible"
              exit="hidden"
              transition={{ duration: 0.2 }}
              className="w-full"
            >
              <Card className="border-destructive/30 bg-destructive/5 shadow-xs">
                <CardContent className="p-6 sm:p-8">
                  <div className="flex flex-col items-center text-center max-w-md mx-auto">
                    <div className="w-12 h-12 rounded-xl bg-destructive/10 flex items-center justify-center mb-4">
                      <AlertCircle className="w-6 h-6 text-destructive" />
                    </div>
                    <h3 className="text-base font-semibold text-foreground mb-1.5">
                      Analysis Failed
                    </h3>
                    <p className="text-xs sm:text-sm text-muted-foreground mb-5 leading-relaxed">
                      {status.error ||
                        "Something went wrong while analyzing the repository."}
                    </p>
                    <Button
                      onClick={handleReset}
                      variant="outline"
                      className="border-border hover:bg-muted cursor-pointer"
                    >
                      <RotateCcw className="w-3.5 h-3.5 mr-2" />
                      Try Again
                    </Button>
                  </div>
                </CardContent>
              </Card>
            </motion.section>
          )}

          {isLoading && (
            <motion.section
              key="loading"
              variants={fadeIn}
              initial="hidden"
              animate="visible"
              exit="hidden"
              transition={{ duration: 0.2 }}
              className="w-full"
            >
              <LoadingSkeleton status={status} />
            </motion.section>
          )}

          {isComplete && result?.metadata && (
            <motion.div
              key="results"
              variants={fadeIn}
              initial="hidden"
              animate="visible"
              transition={{ duration: 0.2 }}
              className="space-y-7 sm:space-y-9"
            >
              {/* Cache indicator with branch info */}
              {isCached && (
                <motion.div
                  initial={{ opacity: 0, y: -6 }}
                  animate={{ opacity: 1, y: 0 }}
                  className="flex items-center justify-start gap-2.5 flex-wrap font-mono text-[10px]"
                >
                  <Badge
                    variant="secondary"
                    className="gap-1.5 px-2.5 py-0.5 bg-primary/10 text-primary border-primary/20"
                  >
                    <Database className="w-3 h-3" />
                    Loaded from cache
                  </Badge>
                  {result.branch && (
                    <Badge variant="outline" className="gap-1.5 px-2.5 py-0.5">
                      <GitBranch className="w-3 h-3" />
                      {result.branch}
                    </Badge>
                  )}
                  <Button
                    variant="ghost"
                    size="sm"
                    onClick={refresh}
                    disabled={isLoading}
                    className="h-6 gap-1 text-xs hover:bg-primary/10 hover:text-primary cursor-pointer"
                  >
                    <RefreshCw className="w-3 h-3" />
                    Refresh
                  </Button>
                </motion.div>
              )}

              <motion.section
                initial={{ opacity: 0, y: 8 }}
                animate={{ opacity: 1, y: 0 }}
                transition={{ duration: 0.2 }}
                className="w-full"
              >
                <AnalysisHeader
                  metadata={result.metadata}
                  branch={result.branch || currentBranch}
                  availableBranches={result.availableBranches}
                  onBranchChange={analyzeBranch}
                  isLoading={isLoading}
                />
              </motion.section>

              {/* Architecture Diagram */}
              <motion.section
                initial={{ opacity: 0, y: 8 }}
                animate={{ opacity: 1, y: 0 }}
                transition={{ duration: 0.2, delay: 0.1 }}
                className="workspace-panel w-full"
              >
                <SectionHeader title="Architecture" icon={GitBranch} />
                <div className="mt-3.5">
                  {result.architecture && result.architecture.length > 0 ? (
                    <ArchitectureDiagram components={result.architecture} />
                  ) : (
                    <EmptyState
                      icon={GitBranch}
                      title="No Architecture Data"
                      description="Architecture visualization is not available for this repository."
                    />
                  )}
                </div>
              </motion.section>

              {/* Dependency Graph */}
              {result.dependencyGraph?.nodes &&
                result.dependencyGraph.nodes.length > 0 && (
                  <motion.section
                    initial={{ opacity: 0, y: 8 }}
                    animate={{ opacity: 1, y: 0 }}
                    transition={{ duration: 0.2, delay: 0.12 }}
                    className="workspace-panel w-full"
                  >
                    <SectionHeader
                      title="Dependency Map"
                      icon={Workflow}
                    />
                    <div className="mt-3.5">
                      <DependencyGraph
                        nodes={result.dependencyGraph.nodes}
                        edges={result.dependencyGraph.edges || []}
                      />
                    </div>
                  </motion.section>
                )}

              {/* Refactors, Automations & Issues Tabs */}
              <motion.section
                initial={{ opacity: 0, y: 8 }}
                animate={{ opacity: 1, y: 0 }}
                transition={{ duration: 0.2, delay: 0.15 }}
                className="workspace-panel w-full"
              >
                <SectionHeader title="Recommendations & Actions" />

                <div className="mt-3.5">
                  <Tabs defaultValue="issues" className="w-full">
                    <ScrollArea className="w-full pb-1">
                      <TabsList
                        className="inline-flex h-10 gap-1 rounded-none border-b border-border bg-transparent p-0"
                      >
                        <TabTriggerItem
                          value="issues"
                          icon={Bug}
                          label="Issues"
                          count={suggestedIssues.length}
                        />
                        <TabTriggerItem
                          value="automations"
                          icon={Zap}
                          label="Automations"
                          count={result.automations?.length}
                        />
                        <TabTriggerItem
                          value="refactors"
                          icon={Wrench}
                          label="Refactors"
                          count={
                            result.refactors?.filter(
                              (r) =>
                                r.title &&
                                r.description &&
                                r.impact &&
                                r.effort,
                            ).length
                          }
                        />
                      </TabsList>
                      <ScrollBar
                        orientation="horizontal"
                        className="invisible"
                      />
                    </ScrollArea>

                    <TabsContent
                      value="refactors"
                      className="mt-4 focus-visible:outline-none"
                    >
                      <motion.div
                        initial={{ opacity: 0 }}
                        animate={{ opacity: 1 }}
                        transition={{ duration: 0.15 }}
                      >
                        <RefactorsPanel
                          refactors={result.refactors || []}
                          repoFullName={result.metadata?.fullName}
                        />
                      </motion.div>
                    </TabsContent>

                    <TabsContent
                      value="automations"
                      className="mt-4 focus-visible:outline-none"
                    >
                      <motion.div
                        initial={{ opacity: 0 }}
                        animate={{ opacity: 1 }}
                        transition={{ duration: 0.15 }}
                      >
                        {result.automations && result.automations.length > 0 ? (
                          <AutomationsPanel
                            automations={result.automations}
                            repoFullName={result.metadata?.fullName}
                          />
                        ) : (
                          <EmptyState
                            icon={Zap}
                            title="No Automation Suggestions"
                            description="No automation opportunities were identified."
                          />
                        )}
                      </motion.div>
                    </TabsContent>

                    <TabsContent
                      value="issues"
                      className="mt-4 focus-visible:outline-none"
                    >
                      <motion.div
                        initial={{ opacity: 0 }}
                        animate={{ opacity: 1 }}
                        transition={{ duration: 0.15 }}
                      >
                        <IssuesPanel
                          repoFullName={result.metadata?.fullName || ""}
                          suggestedIssues={suggestedIssues}
                        />
                      </motion.div>
                    </TabsContent>
                  </Tabs>
                </div>
              </motion.section>

              {/* Reset Button */}
              <motion.section
                initial={{ opacity: 0 }}
                animate={{ opacity: 1 }}
                transition={{ duration: 0.2, delay: 0.2 }}
                className="w-full flex justify-center pt-2 pb-6"
              >
                <Button
                  onClick={handleReset}
                  variant="outline"
                  size="default"
                  className={cn(
                    "group cursor-pointer",
                    "border-border/80 hover:border-border",
                    "hover:bg-muted/50",
                    "transition-all duration-150",
                  )}
                >
                  <RotateCcw
                    className={cn(
                      "w-4 h-4 mr-2 text-muted-foreground",
                      "group-hover:text-foreground",
                      "transition-all",
                    )}
                  />
                  <span className="text-muted-foreground group-hover:text-foreground transition-colors">
                    Analyze Another Repository
                  </span>
                </Button>
              </motion.section>
            </motion.div>
          )}

          {/* Idle State - Recent Analyses */}
          {isIdle && (
            <motion.div
              key="idle"
              initial={{ opacity: 0 }}
              animate={{ opacity: 1 }}
              exit={{ opacity: 0 }}
              className="space-y-6"
            >
              <RecentAnalyses onSelect={analyze} />
              <Card className="gap-0 overflow-hidden rounded-lg border-border bg-card p-0 shadow-none">
                <div className="flex flex-wrap items-center justify-between gap-2 border-b border-border px-4 py-3 sm:px-5">
                  <h2 className="font-mono text-xs font-medium text-foreground">Try a public codebase</h2>
                  <p className="text-[11px] text-muted-foreground">Choose a repository to start an analysis.</p>
                </div>
                <CardContent className="grid gap-3 p-4 sm:grid-cols-3 sm:p-5">
                  {[
                    { name: "React", repo: "facebook/react", category: "UI library", description: "Explore the components and rendering system behind React." },
                    { name: "Next.js", repo: "vercel/next.js", category: "App framework", description: "Follow the connections between routing, rendering, and the server." },
                    { name: "Vite", repo: "vitejs/vite", category: "Build tooling", description: "Inspect the development server, plugin system, and build pipeline." },
                  ].map((repository) => (
                    <button key={repository.repo} type="button" onClick={() => analyze(repository.repo)} className="group flex flex-col rounded-md border border-border bg-card p-4 text-left transition-colors hover:border-primary/50 hover:bg-accent/40 focus-visible:outline-2 focus-visible:outline-ring focus-visible:outline-offset-2">
                      <div className="mb-3 flex w-full items-center justify-between gap-2">
                        <Github className="h-4 w-4 text-muted-foreground" />
                        <span className="font-mono text-[9px] uppercase tracking-wider text-muted-foreground">{repository.category}</span>
                      </div>
                      <h3 className="text-sm font-medium text-foreground">{repository.name}</h3>
                      <span className="mt-1 font-mono text-[10px] text-muted-foreground">{repository.repo}</span>
                      <p className="mt-3 flex-1 text-xs leading-5 text-muted-foreground">{repository.description}</p>
                      <span className="mt-4 inline-flex items-center gap-1.5 text-[11px] font-medium text-primary">Inspect repository<ArrowRight className="h-3 w-3 transition-transform group-hover:translate-x-0.5" /></span>
                    </button>
                  ))}
                </CardContent>
              </Card>
            </motion.div>
          )}
        </AnimatePresence>
      </div>
    </div>
  );
}
